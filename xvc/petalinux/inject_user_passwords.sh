#!/bin/sh
# inject_user_passwords.sh - set the image's account passwords at BUILD time
# without ever committing them.
#
#   ./inject_user_passwords.sh root root      # root/root, xvc/root
#   ./inject_user_passwords.sh                # prompts, no echo
#
# Writes xvc/petalinux/xvc/project-spec/meta-user/conf/secret.conf, which
# petalinux-image-minimal.bbappend includes if it exists. That file is
# gitignored, so the hashes stay off the repo. Run petalinux-build afterwards.
#
# Without this step the recipe falls back to deliberately invalid placeholder
# hashes: the image builds and boots, but nobody can log in.
set -eu

here=$(cd "$(dirname "$0")" && pwd)
confdir="$here/xvc/project-spec/meta-user/conf"
conf="$confdir/secret.conf"

die() { echo "inject_user_passwords: $*" >&2; exit 1; }

command -v openssl >/dev/null 2>&1 || die "openssl not found (needed for SHA-512 hashes)"

ask() {
    # ask <label>; reads one line without echoing
    printf '%s' "$1"
    stty -echo 2>/dev/null || true
    IFS= read -r answer
    stty echo 2>/dev/null || true
    printf '\n'
}

root_pw=${1-}
xvc_pw=${2-}

if [ -z "$root_pw" ]; then
    ask 'root password: '
    root_pw=$answer
    ask 'root password again: '
    [ "$answer" = "$root_pw" ] || die "passwords do not match"
fi
[ -n "$root_pw" ] || die "empty password refused"

if [ -z "$xvc_pw" ] && [ $# -lt 2 ]; then
    ask 'xvc password (unprivileged account, Enter to reuse root): '
    xvc_pw=${answer:-$root_pw}
fi
[ -n "$xvc_pw" ] || die "empty password refused"

# Bitbake expands $... in values, so every '$' in a crypt hash must be escaped
# as '\$'. The bbappend substitutes the variable, which is a single pass, so the
# hash survives intact.
esc() { printf '%s' "$1" | sed 's/\$/\\$/g'; }

root_h=$(openssl passwd -6 "$root_pw")
xvc_h=$(openssl passwd -6 "$xvc_pw")

mkdir -p "$confdir"
umask 077
cat > "$conf" <<EOF
# generated by inject_user_passwords.sh $(date -u +%Y-%m-%dT%H:%M:%SZ) - DO NOT COMMIT
# gitignored on purpose: these are live credentials for the built image.
XJSM_ROOT_PW_HASH = '$(esc "$root_h")'
XJSM_XVC_PW_HASH  = '$(esc "$xvc_h")'
EOF
chmod 600 "$conf"

echo "wrote $conf (mode 600)"
echo "root -> ${root_pw%"${root_pw#?}"}***, xvc -> ${xvc_pw%"${xvc_pw#?}"}***"
echo "now run: petalinux-build"
