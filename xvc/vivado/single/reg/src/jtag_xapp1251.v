// jtag_xapp1251.v - AXI4-Lite to JTAG controller, exactly as XAPP1251 defines it.
//
// Register set (XAPP1251 Table 1) - and nothing else. No FIFO, no DIV register,
// no STATUS register: the TCK rate is a synthesis parameter, as it is a
// packaging option in the app note's IP.
//
//   0x00  LENGTH       R/W  shift length in bits (1..32 per operation)
//   0x04  TMS_VECTOR   R/W  TMS bits, bit0 shifted out first
//   0x08  TDI_VECTOR   R/W  TDI bits, bit0 shifted in first
//   0x0C  TDO_VECTOR   R/W  captured TDO, bit0 = first bit sampled
//   0x10  CTRL         R/W  bit0 = enable shift operation (reads as busy)
//
// Host protocol, per the app note: write LENGTH, TMS_VECTOR and TDI_VECTOR in
// any order, then write CTRL with bit0 set. Poll CTRL until bit0 clears, then
// read TDO_VECTOR. Long scans are the host's business: it splits them into
// <=32-bit operations, which is what makes this the "register" path.
//
// TCK is generated by division, so one bit takes exactly 2*TCK_DIV clocks and
// the TCK duty cycle is fixed by hardware, never by the CPU.

module jtag_xapp1251 #(
    parameter integer TCK_DIV = 5      // half period in clk cycles: TCK = fclk/(2*TCK_DIV)
) (
    input  wire        clk,
    input  wire        rstn,

    // ---- AXI4-Lite slave ----
    input  wire [31:0] s_axi_awaddr,
    input  wire        s_axi_awvalid,
    output wire        s_axi_awready,
    input  wire [31:0] s_axi_wdata,
    input  wire [3:0]  s_axi_wstrb,
    input  wire        s_axi_wvalid,
    output wire        s_axi_wready,
    output reg  [1:0]  s_axi_bresp,
    output reg         s_axi_bvalid,
    input  wire        s_axi_bready,
    input  wire [31:0] s_axi_araddr,
    input  wire        s_axi_arvalid,
    output wire        s_axi_arready,
    output reg  [31:0] s_axi_rdata,
    output reg  [1:0]  s_axi_rresp,
    output reg         s_axi_rvalid,
    input  wire        s_axi_rready,

    // ---- JTAG pins ----
    output reg         tck,
    output reg         tms,
    output reg         tdi,
    input  wire        tdo,

    output wire        busy
);

    localparam [1:0] IDLE = 2'd0, RUN = 2'd1;

    reg [31:0] len_q, tms_q, tdi_q, tdo_q;
    reg [31:0] go_seq;          // incremented by a CTRL write, consumed by the engine
    reg [31:0] seen_seq;

    // ---- AXI4-Lite write channel ----
    reg        aw_done, w_done;
    reg [31:0] waddr, wdata;

    assign s_axi_awready = !aw_done;
    assign s_axi_wready  = !w_done;

    always @(posedge clk) begin
        if (!rstn) begin
            aw_done <= 1'b0; w_done <= 1'b0;
            s_axi_bvalid <= 1'b0; s_axi_bresp <= 2'b00;
            waddr <= 32'd0; wdata <= 32'd0;
            len_q <= 32'd0; tms_q <= 32'd0; tdi_q <= 32'd0;
            go_seq <= 32'd0;
        end else begin
            if (s_axi_bvalid && s_axi_bready) s_axi_bvalid <= 1'b0;

            if (s_axi_awvalid && s_axi_awready) begin
                waddr <= s_axi_awaddr; aw_done <= 1'b1;
            end
            if (s_axi_wvalid && s_axi_wready) begin
                wdata <= s_axi_wdata; w_done <= 1'b1;
            end

            if (aw_done && w_done) begin
                case (waddr[5:2])
                    4'd0: len_q <= wdata;      // 0x00 LENGTH
                    4'd1: tms_q <= wdata;      // 0x04 TMS_VECTOR
                    4'd2: tdi_q <= wdata;      // 0x08 TDI_VECTOR
                    4'd4: if (wdata[0]) go_seq <= go_seq + 32'd1;   // 0x10 CTRL bit0
                    default: ;
                endcase
                aw_done <= 1'b0; w_done <= 1'b0; s_axi_bvalid <= 1'b1;
            end
        end
    end

    /* 0x0C is a capture register: the host may write it, but it must still have
     * exactly one driver. That driver is the engine block below, which takes
     * this write pulse instead of the AXI block assigning tdo_q a second time
     * (two drivers is DRC MDRV-1 and would be a real bus conflict). */
    wire axi_tdo_wr = aw_done && w_done && (waddr[5:2] == 4'd3);

    // ---- AXI4-Lite read channel ----
    assign s_axi_arready = !s_axi_rvalid;
    wire   running = (state == RUN);

    always @(posedge clk) begin
        if (!rstn) begin
            s_axi_rvalid <= 1'b0; s_axi_rdata <= 32'd0; s_axi_rresp <= 2'b00;
        end else begin
            if (s_axi_rvalid && s_axi_rready) s_axi_rvalid <= 1'b0;
            if (s_axi_arvalid && s_axi_arready) begin
                case (s_axi_araddr[5:2])
                    4'd0: s_axi_rdata <= len_q;
                    4'd1: s_axi_rdata <= tms_q;
                    4'd2: s_axi_rdata <= tdi_q;
                    4'd3: s_axi_rdata <= tdo_q;
                    4'd4: s_axi_rdata <= {31'd0, (running | (go_seq != seen_seq))};
                    default: s_axi_rdata <= 32'd0;
                endcase
                s_axi_rvalid <= 1'b1;
            end
        end
    end

    // ---- shift engine ----
    reg [1:0]  state;
    reg [15:0] ph;
    reg [5:0]  bits;
    reg [31:0] sh_tms, sh_tdi, sh_tdo;

    assign busy = running;

    wire [15:0] ph_end  = (TCK_DIV << 1) - 1;
    wire [15:0] ph_rise = TCK_DIV;
    wire [15:0] ph_samp = TCK_DIV + (TCK_DIV >> 1);

    always @(posedge clk) begin
        if (!rstn) begin
            state <= IDLE; tck <= 1'b0; tms <= 1'b0; tdi <= 1'b0;
            ph <= 16'd0; bits <= 6'd0;
            sh_tms <= 32'd0; sh_tdi <= 32'd0; sh_tdo <= 32'd0;
            seen_seq <= 32'd0;
        end else begin
            case (state)
                IDLE: begin
                    tck <= 1'b0;
                    if (go_seq != seen_seq) begin
                        seen_seq <= go_seq;
                        sh_tms <= tms_q;
                        sh_tdi <= tdi_q;
                        sh_tdo <= 32'd0;
                        bits   <= (len_q == 0) ? 6'd1 : len_q[5:0];
                        ph     <= 16'd0;
                        state  <= RUN;
                    end
                end

                RUN: begin
                    if (ph == 16'd0) begin
                        /* set the bit up while TCK is low */
                        tms <= sh_tms[0];
                        tdi <= sh_tdi[0];
                        tck <= 1'b0;
                    end
                    if (ph == ph_rise) tck <= 1'b1;        /* the only rising edge */
                    if (ph == ph_samp) begin
                        sh_tdo <= {tdo, sh_tdo[31:1]};
                        if (bits == 6'd1) tdo_q <= {tdo, sh_tdo[31:1]};
                    end
                    if (axi_tdo_wr) tdo_q <= wdata;          /* host write wins */
                    if (ph == ph_end) begin
                        tck <= 1'b0;                        /* falling edge */
                        ph  <= 16'd0;
                        if (bits == 6'd1) begin
                            state <= IDLE;
                        end else begin
                            bits   <= bits - 6'd1;
                            sh_tms <= sh_tms >> 1;
                            sh_tdi <= sh_tdi >> 1;
                        end
                    end else begin
                        ph <= ph + 16'd1;
                    end
                end

                default: state <= IDLE;
            endcase
        end
    end

endmodule
